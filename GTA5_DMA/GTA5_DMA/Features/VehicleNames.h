inline constexpr std::size_t kVehicleNameCount = sizeof(kVehicleNames) / sizeof(kVehicleNames[0]);

// 按哈希查表（二分查找，表已按哈希升序）；未收录返回 nullptr
inline const VehicleNameEntry* LookupVehicleName(uint32_t hash)
{
    std::size_t lo = 0, hi = kVehicleNameCount;
    while (lo < hi)
    {
        const std::size_t mid = (lo + hi) / 2;
        if (kVehicleNames[mid].hash < hash) lo = mid + 1;
        else hi = mid;
    }
    if (lo < kVehicleNameCount && kVehicleNames[lo].hash == hash)
        return &kVehicleNames[lo];
    return nullptr;
}
